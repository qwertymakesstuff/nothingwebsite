const bell = (n, x, y) => ({
  id: `bell_${n}`, sprite: 'bell', x, y, label: ['', 'I', 'II', 'III', 'IV', 'V', 'VI', 'VII', 'VIII'][n],
  solid: [2, 10, 6, 4], zone: [-3, -2, 16, 22], script: [{ puzzle: ['bells', n] }],
});

const arch = (id, x, dir) => ({
  id, x, y: 2, w: 2, h: 2, zone: [0, 0, 16, 26], label: dir === 'L' ? '◄' : dir === 'R' ? '►' : '▲',
  when: { none: ['maze_solved'] },
  script: [{ say: [`You go through the ${dir === 'L' ? 'left' : dir === 'R' ? 'right' : 'middle'} arch.`], puzzle: ['maze', dir] }],
});

// the ceremony floor: three pairs of plaques, one line of the prayer on each; the crossed-out
// lines on the prayer card are the ones that must not be stood on
const WRONG = {
  say: ['The floor tips under you. Hands come up through the stone and pull.', 'You are back at the foot of the floor.'],
  hurt: 1, glitch: 16, shake: true, sfx: 'whisper',
  go: { to: 'sanctum', spawn: 'floor_start' },
};
const plaque = (id, x, y, text, right) => ({
  id: 'plaque_' + id, sprite: right ? 'plaque' : 'plaque_b', x, y, zone: [0, 0, 16, 32],
  script: [{ say: [`Cut into the stone: ${text}`] }],
});
const step = (id, x, y) => ({ id: 'step_' + id, x, y, w: 2, h: 2, script: [WRONG] });
const holds = (id, x, y) => ({ id: 'holds_' + id, on: 'zone', zone: { x, y, w: 2, h: 2 }, say: ['The stone holds. It is warm, like a hand.'], sfx: 'bell' });

