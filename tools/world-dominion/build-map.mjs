// Builds world-dominion/js/data/world.js: pre-projected SVG country shapes, label points, bounding boxes,
// land-border neighbours and a map colouring, so the game needs no map library at runtime (and works offline).
//
// Source: Natural Earth 1:110m admin-0 countries (public domain) via the world-atlas package (ISC).
//
// The site has no package.json, so install the generator's dependencies anywhere outside the repo and pass
// that folder:
//   mkdir -p /tmp/wd-map && (cd /tmp/wd-map && npm init -y && npm i world-atlas@2 topojson-client@3 d3-geo@3)
//   node tools/world-dominion/build-map.mjs /tmp/wd-map
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const depsDir = resolve(process.argv[2] || '.');
const require = createRequire(depsDir + '/');
const topo = require('world-atlas/countries-110m.json');
const topojson = require('topojson-client');
const d3 = await import(require.resolve('d3-geo'));

const W = 1600, H = 820, PAD = 10;
const DROP = new Set(['010', '260']); // Antarctica, Fr. S. Antarctic Lands — not playable nations
const NO_ID = { 'N. Cyprus': 'x-ncy', Somaliland: 'x-sol', Kosovo: 'x-kos' };
const NAMES = {
  'United States of America': 'United States', 'Dem. Rep. Congo': 'DR Congo', 'Central African Rep.': 'Central African Republic',
  'Bosnia and Herz.': 'Bosnia and Herzegovina', 'Dominican Rep.': 'Dominican Republic', 'Eq. Guinea': 'Equatorial Guinea',
  'S. Sudan': 'South Sudan', 'Solomon Is.': 'Solomon Islands', 'Falkland Is.': 'Falkland Islands', 'W. Sahara': 'Western Sahara',
  'N. Cyprus': 'Northern Cyprus', eSwatini: 'Eswatini', Macedonia: 'North Macedonia', 'Timor-Leste': 'East Timor',
};

const geoms = topo.objects.countries.geometries;
const keep = geoms.map((g, i) => ({ g, i })).filter(({ g }) => !DROP.has(g.id));
const neighbourIdx = topojson.neighbors(geoms);
const idOf = (g) => g.id || NO_ID[g.properties.name];

const features = topojson.feature(topo, { type: 'GeometryCollection', geometries: keep.map((k) => k.g) }).features;
const projection = d3.geoNaturalEarth1().fitExtent([[PAD, PAD], [W - PAD, H - PAD]], { type: 'FeatureCollection', features });
const path = d3.geoPath(projection);
const r1 = (n) => Math.round(n * 10) / 10;
const compact = (d) => (d || '').replace(/(\d+\.\d)\d+/g, '$1');

const countries = features.map((f, n) => {
  const { g, i } = keep[n];
  // label + camera framing use the largest landmass (keeps Alaska, Guiana, Chukotka from skewing the centre)
  const polys = f.geometry.type === 'MultiPolygon' ? f.geometry.coordinates.map((c) => ({ type: 'Polygon', coordinates: c })) : [f.geometry];
  const main = polys.map((p) => ({ p, a: path.area(p) })).sort((a, b) => b.a - a.a)[0].p;
  const [cx, cy] = path.centroid(main);
  const [[x0, y0], [x1, y1]] = path.bounds(main);
  return {
    id: idOf(g),
    name: NAMES[g.properties.name] || g.properties.name,
    d: compact(path(f)),
    cx: r1(cx), cy: r1(cy),
    box: [r1(x0), r1(y0), r1(x1), r1(y1)],
    area: Math.round(path.area(f)),
    neighbors: [...new Set(neighbourIdx[i].filter((j) => j !== i).map((j) => geoms[j]).filter((x) => !DROP.has(x.id)).map(idOf))],
  };
});

// Greedy graph colouring so bordering countries never share a tint (highest-degree first).
const byId = new Map(countries.map((c) => [c.id, c]));
const PALETTE_SIZE = 6;
[...countries].sort((a, b) => b.neighbors.length - a.neighbors.length || b.area - a.area).forEach((c) => {
  const used = new Set(c.neighbors.map((id) => byId.get(id)?.tint).filter((t) => t !== undefined));
  let t = 0; while (used.has(t) && t < PALETTE_SIZE - 1) t++;
  c.tint = t;
});

const graticule = compact(path(d3.geoGraticule10()));
const outline = compact(path({ type: 'Sphere' }));
const out = `// GENERATED by tools/world-dominion/build-map.mjs — do not edit by hand.
// Natural Earth 1:110m admin-0 countries (public domain), Natural Earth projection, ${W}x${H}.
export const MAP_W = ${W};
export const MAP_H = ${H};
export const OUTLINE = ${JSON.stringify(outline)};
export const GRATICULE = ${JSON.stringify(graticule)};
export const COUNTRIES = [
${countries.sort((a, b) => a.name.localeCompare(b.name)).map((c) => JSON.stringify(c)).join(',\n')}
];
`;
const target = fileURLToPath(new URL('../../world-dominion/js/data/world.js', import.meta.url));
writeFileSync(target, out);
console.log(`wrote ${countries.length} countries, ${(out.length / 1024).toFixed(0)} KB -> ${target}`);
