// characters with no glyph of their own
const ALIAS = { '…': '...', '—': '-', '–': '-', '’': "'", '‘': "'", '“': '"', '”': '"' };

export const GLYPHS = {};
for (const [ch, src] of Object.entries(SRC)) {
  const rows = src ? src.split(' ') : [];
  const bits = new Uint8Array(GLYPH_W * GLYPH_H);
  rows.forEach((row, y) => { for (let x = 0; x < GLYPH_W; x++) if (row[x] === '#') bits[y * GLYPH_W + x] = 1; });
  GLYPHS[ch] = bits;
}

export function normalize(str) {
  let out = '';
  for (const ch of String(str)) out += ch === '\n' ? ch : ALIAS[ch] ?? (GLYPHS[ch] ? ch : (GLYPHS[ch.toUpperCase()] ? ch.toUpperCase() : '?'));
  return out;
}

export const textWidth = (str, scale = 1) => {
  const n = [...normalize(str)].length;
  return n ? (n * ADVANCE - 1) * scale : 0;
};

// word wrap to a character budget; honours explicit newlines
export function wrap(str, maxChars) {
  const out = [];
  for (const para of normalize(str).split('\n')) {
    let line = '';
    for (const word of para.split(' ')) {
      if (!line.length) line = word;
      else if (line.length + 1 + word.length <= maxChars) line += ' ' + word;
      else { out.push(line); line = word; }
      while (line.length > maxChars) { out.push(line.slice(0, maxChars)); line = line.slice(maxChars); }
    }
    out.push(line);
  }
  return out;
}
