#!/usr/bin/env node
// Converts puzzles.jsonl (from generate.mjs) into a Supabase migration that inserts them.
// Idempotent: existing puzzles are left alone (their ratings keep what players' attempts taught them).
// Usage: node to-sql.mjs puzzles.jsonl ../db/supabase/migrations/<timestamp>_puzzles.sql
import { readFileSync, writeFileSync } from 'node:fs';
import { Chess } from 'chess.js';

const [input, output] = process.argv.slice(2);
const UCI = /^[a-h][1-8][a-h][1-8][qrbn]?$/;
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const rows = [];
for (const line of readFileSync(input, 'utf8').split('\n').filter(Boolean)) {
  const p = JSON.parse(line);
  // Re-verify legality of every move before it goes into the database.
  const chess = new Chess(p.fen);
  for (const m of p.moves) {
    if (!UCI.test(m)) throw new Error(`bad move ${m} in ${p.id}`);
    chess.move({ from: m.slice(0, 2), to: m.slice(2, 4), promotion: m[4] });
  }
  const [first, ...solution] = p.moves;
  if (solution.length % 2 !== 1) throw new Error(`solution must end on the solver's move: ${p.id}`);
  // Initial deviation 150: the engine-based estimate is informative but not certain; attempts refine it.
  rows.push(`(${q(p.id)}, ${q(p.fen)}, ${q(first)}, array[${solution.map(q).join(',')}], ${p.rating}, 150, ${'array[' + p.themes.map(q).join(',') + ']::text[]'})`);
}
const sql = `-- Rookery puzzles, generated by packages/puzzles/generate.mjs from Stockfish self-play games and
-- verified move by move (see that script). ${rows.length} puzzles. Re-running inserts only new ones.
insert into public.puzzles (id, fen, first_move, solution, rating, rd, themes) values
${rows.join(',\n')}
on conflict (id) do nothing;
`;
writeFileSync(output, sql);
console.log(`${rows.length} puzzles → ${output}`);
