// LAST EXIT: builds the voice-acting paperwork from the dialogue database, so it can never drift from what the game says.
//   node gta/tools/voice.mjs          writes  gta/VOICE_SCRIPT.md   (the master script for the actors)
//                                             gta/voice/manifest.json   (every line that can be recorded, and whether a recording exists)
//                                             gta/voice/available.json  (the small list of lines that do have a recording; the game loads this one)
//   node gta/tools/voice.mjs --check  exits 1 if either file is out of date (the tests run this)
// A recording "exists" only if a real file is in gta/voice/<CHARACTER>/<LINE_ID>.ogg (or .mp3). Nothing here records or synthesises
// a voice. Direction for the actor is written separately from the spoken text and never reaches the game screen.
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const { SCENES, LINES } = await import(new URL('js/story/lines/index.js', root));
const { CAST, SPEAKERS } = await import(new URL('js/story/cast.js', root));
const { MISSION_LIST, HANGOUTS } = await import(new URL('js/story/missions.js', root));
const { readSeconds, sceneLineIds } = await import(new URL('js/story/dialogue.js', root));

/* which missions use which scene */
const usedBy = {};
const use = (sc, m) => { if (sc && SCENES[sc]) (usedBy[sc] = usedBy[sc] || new Set()).add(m); };
for (const m of MISSION_LIST) {
  use(m.announce, m.id); if (m.onDone && m.onDone.call) use(m.onDone.call, m.id);
  for (const st of m.steps) for (const sc of [].concat(st.scene || [], st.radio || [])) use(sc, m.id);
}
for (const h of HANGOUTS) for (const x of h.scenes) use(x.s, 'HANGOUT');
for (const sc of Object.values(SCENES)) if (!usedBy[sc.id]) (usedBy[sc.id] = new Set()).add(/^X0\d$/.test(sc.mission) ? 'RADIO' : sc.mission);
const missionTitle = id => { const m = MISSION_LIST.find(x => x.id === id); return m ? m.code : id === 'HANGOUT' ? 'HANGOUT (talk to people in the city)' : id === 'RADIO' ? 'CAR RADIO (Alder FM and Harbor AM broadcasts)' : id; };

/* recordings on disk */
const voiceDir = new URL('voice/', root), found = new Map();
if (fs.existsSync(voiceDir)) for (const ch of fs.readdirSync(voiceDir, { withFileTypes: true })) if (ch.isDirectory())
  for (const f of fs.readdirSync(new URL(ch.name + '/', voiceDir))) { const m = f.match(/^(.+)\.(ogg|mp3)$/i); if (m) found.set(m[1], ch.name + '/' + f); }

const ids = Object.keys(LINES).sort((a, b) => (LINES[a].char + LINES[a].scene).localeCompare(LINES[b].char + LINES[b].scene) || a.localeCompare(b));
const words = t => t.trim().split(/\s+/).length;

/* ---- manifest ---- */
const lines = ids.map(id => {
  const l = LINES[id], sc = SCENES[l.scene], f = found.get(id);
  return { id, character: l.char, scene: l.scene, via: l.via, missions: [...(usedBy[l.scene] || [])].sort(), file: f || l.char + '/' + id + '.ogg', exists: !!f, text: l.text.en, direction: l.dir, words: words(l.text.en), seconds: +readSeconds(l.text.en).toFixed(1), filter: (l.via === 'phone' || l.via === 'radio') && !sc.unfiltered };
});
const byChar = {}; for (const l of lines) { const c = (byChar[l.character] = byChar[l.character] || { lines: 0, recorded: 0, words: 0 }); c.lines++; c.words += l.words; if (l.exists) c.recorded++; }
const manifest = { format: 1, note: 'Generated by gta/tools/voice.mjs from the dialogue database. "exists" is true only when a real recording file is present in gta/voice/. The game plays every line with or without one.', locale: 'en', total: lines.length, recorded: lines.filter(l => l.exists).length, characters: byChar, lines };

/* ---- master script ---- */
const out = [];
out.push('# LAST EXIT: master voice script', '');
out.push('Every line of spoken dialogue in the game, by character, with its ID, performance direction and where it is heard. **No line is recorded yet** unless the manifest says so; the game is fully playable with subtitles only.', '');
out.push(`Lines: **${lines.length}** across **${Object.keys(byChar).length}** characters. Recorded so far: **${manifest.recorded}** of ${lines.length}.`, '');
out.push('## How to deliver recordings', '',
  '- One file per line, named exactly after the line ID: `gta/voice/<CHARACTER>/<LINE_ID>.ogg` (Ogg Vorbis, mono, 44.1 kHz, about -16 LUFS, peaks under -1 dBFS). `.mp3` is also accepted.',
  '- Record **dry**: no reverb, no added room tone. The game adds the phone/radio filter itself where a line is marked **filtered**.',
  '- Leave about 0.2 s of silence at the start and end of each file; trim the rest.',
  '- Read only the **spoken text**. The *direction* is for you and is never shown to the player.',
  '- After adding files run `node gta/tools/voice.mjs`, which marks them in `gta/voice/manifest.json`. The game then plays them automatically.',
  '- Test any single line in the game: pause, open "test a line of dialogue", type the line ID.', '');
out.push('## Characters', '', '| Character | Role | Lines | Words | About |', '|---|---|---:|---:|---|');
for (const c of SPEAKERS) if (byChar[c]) out.push(`| ${CAST[c].name} (\`${c}\`) | ${CAST[c].role || ''} | ${byChar[c].lines} | ${byChar[c].words} | ${Math.round(byChar[c].words / 2.6 / 60)} min |`);
out.push('');
for (const c of SPEAKERS) {
  if (!byChar[c]) continue; const p = CAST[c], v = p.voice || {}, mine = lines.filter(l => l.character === c);
  out.push(`## ${p.name} (\`${c}\`)`, '');
  out.push(`**Role:** ${p.role || ''}  `, `**Voice:** ${v.description || ''}  `, `**Direction:** ${v.direction || ''}  `, `**Accent:** ${v.accent || ''}  `, `**Pace:** ${v.pace || ''}  `, `**Range:** ${v.range || ''}  `);
  if (v.pronunciation && v.pronunciation.length) out.push(`**Pronunciation:** ${v.pronunciation.join('; ')}  `);
  out.push(`**Recording notes:** ${v.recording || ''}`, '');
  if (p.bio) out.push(`**Who they are:** ${p.bio}`, '');
  if (p.motivation) out.push(`**Wants:** ${p.motivation}  `, `**Fears:** ${p.fear || ''}  `, `**Hides:** ${p.hides || ''}  `, `**Arc:** ${p.arc || ''}`, '');
  out.push(`${mine.length} lines, ${byChar[c].words} words.`, '');
  let curScene = null;
  for (const l of mine.slice().sort((a, b) => a.scene.localeCompare(b.scene) || a.id.localeCompare(b.id))) {
    if (l.scene !== curScene) { curScene = l.scene; const sc = SCENES[l.scene]; out.push(`### ${l.scene}`, `*${missionTitle(l.missions[0])}${l.missions.length > 1 ? ' +' + (l.missions.length - 1) : ''}; heard ${sc.via === 'direct' ? 'face to face' : sc.via === 'car' ? 'in the car' : 'over the ' + sc.via}${l.filter ? ', **filtered** (record dry)' : ''}${sc.as ? '; shown as "' + sc.as + '"' : ''}*`, ''); }
    out.push(`- \`${l.id}\`${l.exists ? ' ✅' : ''}  `, `  *Direction:* ${l.direction}  `, `  **Say:** ${l.text}`, '');
  }
}
out.push('## Master list by mission', '', 'Which recordings each part of the story needs.', '');
const per = {}; for (const l of lines) for (const m of l.missions) (per[m] = per[m] || []).push(l);
for (const m of Object.keys(per).sort()) { const n = per[m].length, r = per[m].filter(l => l.exists).length; out.push(`- **${missionTitle(m)}**: ${n} lines, ${r} recorded`); }
out.push('');
const script = out.join('\n');

const available = { format: 1, note: 'Small file the game loads at start: only lines that have a real recording. Generated by gta/tools/voice.mjs.', files: Object.fromEntries(lines.filter(l => l.exists).map(l => [l.id, l.file])) };
const files = [[new URL('VOICE_SCRIPT.md', root), script], [new URL('voice/manifest.json', root), JSON.stringify(manifest, null, 1) + '\n'], [new URL('voice/available.json', root), JSON.stringify(available, null, 1) + '\n']];
if (process.argv.includes('--check')) {
  let bad = 0; for (const [u, text] of files) if (!fs.existsSync(u) || fs.readFileSync(u, 'utf8') !== text) { console.error('out of date: ' + fileURLToPath(u) + ' (run node gta/tools/voice.mjs)'); bad++; }
  process.exit(bad ? 1 : 0);
}
fs.mkdirSync(voiceDir, { recursive: true });
for (const [u, text] of files) fs.writeFileSync(u, text);
console.log(`voice script: ${lines.length} lines, ${manifest.recorded} recorded; wrote VOICE_SCRIPT.md and voice/manifest.json`);
